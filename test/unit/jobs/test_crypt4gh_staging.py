class TestPrepareCrypt4GHInput:
    """Verify the crypt4gh_staging.prepare_crypt4gh_input function."""

    def test_staged_file_starts_with_crypt4gh_magic(self, mock_recryptor, crypt4gh_test_dataset, tmp_path):
        """The staged file must start with the crypt4gh magic bytes."""
        result = prepare_crypt4gh_input(
            dataset=crypt4gh_test_dataset,
            reencryption_service_url=mock_recryptor.url,
            working_directory=str(tmp_path),
            key_config_path=str(_C4GH_TEST_DIR / "crypt4ghfs_test.conf"),
        )
        with open(result.staged_path, "rb") as f:
            assert f.read(8) == b"crypt4gh", "Staged file must start with crypt4gh magic"

    def test_staged_file_is_decryptable_with_compute_key(self, mock_recryptor, crypt4gh_test_dataset, tmp_path):
        """The staged file's body (original encrypted content) must remain intact
        and the new header must be decryptable with the compute private key."""
        result = prepare_crypt4gh_input(
            dataset=crypt4gh_test_dataset,
            reencryption_service_url=mock_recryptor.url,
            working_directory=str(tmp_path),
            key_config_path=str(_C4GH_TEST_DIR / "crypt4ghfs_test.conf"),
        )
        compute_sk = get_private_key(_COMPUTE_SEC, lambda: b"")
        with open(result.staged_path, "rb") as infile:
            outstream = io.BytesIO()
            crypt4gh.lib.decrypt([(0, compute_sk, None)], infile, outstream)
        decrypted = outstream.getvalue()
        # The original plaintext was a small FASTQ snippet
        assert decrypted != b"", "Decryption must yield non-empty content"
        assert b"@read" in decrypted or decrypted  # just verify it decrypted OK

    def test_staged_file_body_equals_original_body(self, mock_recryptor, crypt4gh_test_dataset, tmp_path):
        """The encrypted body in the staged file must be byte-for-byte identical
        to the original (only the header is replaced)."""
        result = prepare_crypt4gh_input(
            dataset=crypt4gh_test_dataset,
            reencryption_service_url=mock_recryptor.url,
            working_directory=str(tmp_path),
            key_config_path=str(_C4GH_TEST_DIR / "crypt4ghfs_test.conf"),
        )

        with open(result.staged_path, "rb") as f:
            staged_content = f.read()

        # Find header boundary in staged file
        staged_stream = io.BytesIO(staged_content)
        list(crypt4gh.header.parse(staged_stream))
        staged_header_end = staged_stream.tell()
        staged_body = staged_content[staged_header_end:]

        # Find header boundary in original file
        with open(_TEST_C4GH_FILE, "rb") as f:
            original_content = f.read()
        orig_stream = io.BytesIO(original_content)
        list(crypt4gh.header.parse(orig_stream))
        orig_header_end = orig_stream.tell()
        original_body = original_content[orig_header_end:]

        assert staged_body == original_body, "Re-staged file body must be identical to the original encrypted body"

    def test_prepare_fails_without_metadata(self, mock_recryptor, tmp_path):
        """prepare_crypt4gh_input must raise if crypt4gh_header metadata is missing."""
        mock_metadata = MagicMock()
        mock_metadata.crypt4gh_header = None
        mock_dataset = MagicMock()
        mock_dataset.id = 99
        mock_dataset.metadata = mock_metadata
        mock_dataset.get_file_name.return_value = _TEST_C4GH_FILE

        with pytest.raises(JobPreparationException, match="missing crypt4gh_header metadata"):
            prepare_crypt4gh_input(
                dataset=mock_dataset,
                reencryption_service_url=mock_recryptor.url,
                working_directory=str(tmp_path),
                key_config_path=str(_C4GH_TEST_DIR / "crypt4ghfs_test.conf"),
            )

    def test_prepare_fails_on_service_error(self, crypt4gh_test_dataset, tmp_path):
        """prepare_crypt4gh_input must raise if the re-encryptor service is unreachable."""
        with pytest.raises(JobPreparationException, match="Failed to contact"):
            prepare_crypt4gh_input(
                dataset=crypt4gh_test_dataset,
                reencryption_service_url="http://127.0.0.1:1",  # No server here
                working_directory=str(tmp_path),
                key_config_path=str(_C4GH_TEST_DIR / "crypt4ghfs_test.conf"),
            )

    def test_staged_directories_created(self, mock_recryptor, crypt4gh_test_dataset, tmp_path):
        """Both the stage_dir and mount_dir should be created, and the per-dataset conf written."""
        result = prepare_crypt4gh_input(
            dataset=crypt4gh_test_dataset,
            reencryption_service_url=mock_recryptor.url,
            working_directory=str(tmp_path),
            key_config_path=str(_C4GH_TEST_DIR / "crypt4ghfs_test.conf"),
        )
        assert os.path.isdir(result.stage_dir)
        assert os.path.isdir(result.mount_dir)
        assert os.path.isfile(result.staged_path)
        assert os.path.isfile(result.dataset_conf_path), "Per-dataset crypt4ghfs conf must be written"


