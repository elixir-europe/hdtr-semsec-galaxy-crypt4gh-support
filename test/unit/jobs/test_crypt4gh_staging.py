class TestMockRecryptorService:
    """Verify that the mock service correctly re-encrypts headers and complies
    with the real service API contract."""

    def test_info_endpoint(self, mock_recryptor):
        """GET /info should return service metadata."""
        response = requests.get(f"{mock_recryptor.url}/info", timeout=5)
        assert response.status_code == 200
        data = response.json()
        assert data["name"] == "mock-crypt4gh-recryptor"

    def test_recrypt_header_returns_valid_response(self, mock_recryptor, crypt4gh_test_dataset):
        """POST /recrypt_header should return all required fields."""
        header_b64 = crypt4gh_test_dataset.metadata.crypt4gh_header
        response = requests.post(
            f"{mock_recryptor.url}/recrypt_header",
            json={"crypt4gh_header": header_b64},
            timeout=10,
        )
        assert response.status_code == 200, response.text
        data = response.json()
        # Check all required fields are present (matches UserRecryptResponse schema)
        assert "crypt4gh_header" in data
        assert "crypt4gh_compute_keypair_id" in data
        assert "crypt4gh_compute_keypair_expiration_date" in data

    def test_recrypt_header_produces_valid_crypt4gh_header(self, mock_recryptor, crypt4gh_test_dataset):
        """The returned re-encrypted header must start with the crypt4gh magic."""
        header_b64 = crypt4gh_test_dataset.metadata.crypt4gh_header
        response = requests.post(
            f"{mock_recryptor.url}/recrypt_header",
            json={"crypt4gh_header": header_b64},
            timeout=10,
        )
        assert response.status_code == 200
        new_header_bytes = base64.b64decode(response.json()["crypt4gh_header"])
        assert new_header_bytes.startswith(b"crypt4gh"), "Re-encrypted header must start with crypt4gh magic bytes"
        # Must be parse-able as a crypt4gh header
        stream = io.BytesIO(new_header_bytes)
        packets = list(crypt4gh.header.parse(stream))
        assert len(packets) >= 1

    def test_recrypt_header_compute_keypair_id_is_stable(self, mock_recryptor, crypt4gh_test_dataset):
        """The mock always returns the same compute keypair ID."""
        header_b64 = crypt4gh_test_dataset.metadata.crypt4gh_header
        response = requests.post(
            f"{mock_recryptor.url}/recrypt_header",
            json={"crypt4gh_header": header_b64},
            timeout=10,
        )
        assert response.json()["crypt4gh_compute_keypair_id"] == "mock-compute-key-1"

    def test_recrypt_header_bad_request_returns_400(self, mock_recryptor):
        """Non-crypt4gh payload should return HTTP 400."""
        not_a_header = base64.b64encode(b"this is not a crypt4gh header").decode("ascii")
        response = requests.post(
            f"{mock_recryptor.url}/recrypt_header",
            json={"crypt4gh_header": not_a_header},
            timeout=10,
        )
        assert response.status_code == 400


